_RECENT = {}  # 事件 -> 最近用过的一条，避免连续重复


def pick_line(event):
    pool = LINES.get(event)
    if not pool:
        return ""
    if event not in _RECENT:
        _RECENT[event] = 0
    idx = _RECENT[event]
    line = pool[idx]
    _RECENT[event] = (idx + 1) % len(pool)
    return line


def greeting_for_hour(hour):
    if 6 <= hour < 12:
        return pick_line("greet_morning")
    if 12 <= hour < 18:
        return pick_line("greet_noon")
    if 18 <= hour < 23:
        return pick_line("greet_evening")
    return pick_line("greet_night")
